export const localeFor = value => value?.startsWith('zh') ? 'zh-CN' : 'en-US';

export function format(template, params = {}) {
  return String(template ?? '').replace(/\{(\w+)\}/g, (_match, key) => (
    params[key] !== undefined ? String(params[key]) : `{${key}}`
  ));
}
